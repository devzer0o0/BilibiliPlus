import 'dart:async';

import 'package:PiliPlus/common/widgets/custom_icon.dart';
import 'package:PiliPlus/common/widgets/native_liquid_glass_navigation_bar.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:material_ui/material_ui.dart';

const _home = NativeLiquidGlassDestination(
  id: 'home',
  label: '首页',
  icon: Icons.home_outlined,
  selectedIcon: Icons.home_rounded,
);

const _dynamics = NativeLiquidGlassDestination(
  id: 'dynamics',
  label: '动态',
  icon: CustomIcons.motion_photos_on_outlined,
  selectedIcon: CustomIcons.motion_photos_on,
  badgeVisible: true,
  badgeText: '99+',
  accessibilityValue: '120 条未读',
);

const _mine = NativeLiquidGlassDestination(
  id: 'mine',
  label: '我的',
  icon: Icons.person_rounded,
  selectedIcon: Icons.person_rounded,
  isAvatar: true,
);

Widget _app(Widget child) {
  return MediaQuery(
    data: const MediaQueryData(
      size: Size(420, 912),
      devicePixelRatio: 3,
      padding: EdgeInsets.only(top: 47, bottom: 34),
    ),
    child: Directionality(
      textDirection: TextDirection.ltr,
      child: Material(
        child: Align(alignment: Alignment.bottomCenter, child: child),
      ),
    ),
  );
}

Widget _bar({
  List<NativeLiquidGlassDestination> destinations = const [
    _home,
    _dynamics,
    _mine,
  ],
  String selectedId = 'home',
  ValueChanged<int>? onSelected,
  VoidCallback? onUnavailable,
  String avatarUrl = '',
  Future<Uint8List?> Function(String url)? avatarLoader,
  bool visible = true,
}) {
  return NativeLiquidGlassNavigationBar(
    destinations: destinations,
    selectedId: selectedId,
    onDestinationSelected: onSelected ?? (_) {},
    onUnavailable: onUnavailable ?? () {},
    avatarUrl: avatarUrl,
    avatarLoader: avatarLoader,
    visible: visible,
    iconRasterizer: (icon, size, pixelRatio) async =>
        Uint8List.fromList([icon.codePoint & 0xff]),
  );
}

class _Bridge {
  _Bridge();

  int viewId = 0;
  final List<MethodCall> viewCalls = <MethodCall>[];
  int createCount = 0;

  TestDefaultBinaryMessenger get _messenger =>
      TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;

  MethodChannel get channel =>
      MethodChannel('piliplus/native_liquid_glass_nav/$viewId');

  /// The platform-view id is generated by the framework, so the instance
  /// channel can only be mocked once create reveals it.
  void install() {
    _messenger.setMockMethodCallHandler(
      SystemChannels.platform_views,
      (call) async {
        if (call.method == 'create') {
          createCount++;
          final args = call.arguments as Map;
          viewId = args['id'] as int;
          _messenger.setMockMethodCallHandler(channel, (call) async {
            viewCalls.add(call);
            if (call.method == 'describe') {
              return {'material': 'UIGlassEffect.clear'};
            }
            return null;
          });
        }
        return null;
      },
    );
  }

  Future<void> sendTap(String id) async {
    await _messenger.handlePlatformMessage(
      channel.name,
      const StandardMethodCodec().encodeMethodCall(
        MethodCall('onTap', {'id': id}),
      ),
      (_) {},
    );
  }

  List<Map<String, Object?>> get states => [
    for (final call in viewCalls)
      if (call.method == 'updateState')
        Map<String, Object?>.from(call.arguments as Map),
  ];

  Map<String, Object?> get lastState => states.last;

  List<Map<String, Object?>> get lastItems => [
    for (final item in lastState['items'] as List)
      Map<String, Object?>.from(item as Map),
  ];

  void clear() {
    viewCalls.clear();
  }
}

/// pumpAndSettle alone can stop before the platform channel answers; idle()
/// drains the microtasks the mock messenger uses.
Future<void> _settle(WidgetTester tester, [_Bridge? bridge]) async {
  await tester.pumpAndSettle();
  // A round trip through the instance channel gives the create future and the
  // state call the messenger step that pumpAndSettle alone does not.
  await (bridge?.channel ?? SystemChannels.platform_views).invokeMethod<void>(
    '_settle',
  );
  await tester.pumpAndSettle();
}

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  tearDown(() {
    TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger
        .setMockMethodCallHandler(SystemChannels.platform_views, null);
    NativeLiquidGlassNavigation.debugResetCapabilities();
  });

  testWidgets('one platform view, stable ids and the shared icon codepoints', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    await tester.pumpWidget(_app(_bar()));
    await _settle(tester, bridge);

    expect(bridge.createCount, 1);
    final state = bridge.lastState;
    expect(state['selectedId'], 'home');
    expect(state['pixelRatio'], 3.0);
    expect(state['style'], 'clear');
    expect(state['visible'], isTrue);
    expect(bridge.lastItems.map((item) => item['id']).toList(), [
      'home',
      'dynamics',
      'mine',
    ]);
    expect(bridge.lastItems.map((item) => item['label']).toList(), [
      '首页',
      '动态',
      '我的',
    ]);
    expect(bridge.lastItems[2]['isAvatar'], isTrue);
    final badge = bridge.lastItems[1]['badge'] as Map;
    expect(badge['visible'], isTrue);
    expect(badge['text'], '99+');
    expect(badge['isDot'], isFalse);
    expect(bridge.lastItems[1]['accessibilityValue'], '120 条未读');

    // The 动态 glyph is the project's own 0xe80b / 0xe80a, rasterised once and
    // keyed by glyph + size + pixel ratio.
    final iconKeys = bridge.states
        .expand((state) => (state['icons'] as Map).keys)
        .cast<String>()
        .toList();
    expect(iconKeys.any((key) => key.contains('e80b')), isTrue);
    expect(iconKeys.any((key) => key.contains('e80a')), isTrue);
    expect(iconKeys.any((key) => key.contains(':23.0:3.00')), isTrue);
    expect(
      bridge.channel.name,
      'piliplus/native_liquid_glass_nav/${bridge.viewId}',
    );
  });

  testWidgets('taps resolve against the ordering that is on screen', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    final taps = <int>[];
    await tester.pumpWidget(_app(_bar(onSelected: taps.add)));
    await _settle(tester, bridge);

    await tester.pumpWidget(
      _app(
        _bar(
          destinations: const [_mine, _dynamics, _home],
          onSelected: taps.add,
        ),
      ),
    );
    await _settle(tester, bridge);

    await bridge.sendTap('home');
    expect(taps, [2]);
    await bridge.sendTap('mine');
    expect(taps, [2, 0]);
    // Reordered-away / hidden entry: no index is guessed.
    await bridge.sendTap('missing');
    expect(taps, [2, 0]);
  });

  testWidgets('a repeated tap on the selected entry is still forwarded', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    final taps = <int>[];
    await tester.pumpWidget(_app(_bar(onSelected: taps.add)));
    await _settle(tester, bridge);

    await bridge.sendTap('dynamics');
    await bridge.sendTap('dynamics');
    expect(taps, [1, 1]);
  });

  testWidgets('selection and unread are incremental state updates', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    await tester.pumpWidget(_app(_bar()));
    await _settle(tester, bridge);
    expect(bridge.createCount, 1);

    bridge.clear();
    await tester.pumpWidget(_app(_bar(selectedId: 'dynamics')));
    await _settle(tester, bridge);

    // Same platform view: no rebuild of the bar, one state update.
    expect(bridge.createCount, 1);
    expect(bridge.states.length, 1);
    expect(bridge.lastState['selectedId'], 'dynamics');
  });

  testWidgets('a stale avatar result never replaces the current one', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    final requests = <String, Completer<Uint8List?>>{};
    Future<Uint8List?> loader(String url) {
      final completer = Completer<Uint8List?>();
      requests[url] = completer;
      return completer.future;
    }

    await tester.pumpWidget(
      _app(
        _bar(avatarUrl: 'https://example.invalid/a.jpg', avatarLoader: loader),
      ),
    );
    await _settle(tester, bridge);
    expect(requests.keys, ['https://example.invalid/a.jpg']);

    await tester.pumpWidget(
      _app(
        _bar(avatarUrl: 'https://example.invalid/b.jpg', avatarLoader: loader),
      ),
    );
    await _settle(tester, bridge);

    requests['https://example.invalid/b.jpg']!.complete(
      Uint8List.fromList([2, 2, 2]),
    );
    await _settle(tester, bridge);
    requests['https://example.invalid/a.jpg']!.complete(
      Uint8List.fromList([1, 1, 1]),
    );
    await _settle(tester, bridge);

    final state = bridge.lastState;
    expect(state['avatarToken'], 'https://example.invalid/b.jpg');
    expect((state['avatar'] as Uint8List).toList(), [2, 2, 2]);
  });

  testWidgets('dispose detaches the channel and drops late taps', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    final taps = <int>[];
    await tester.pumpWidget(_app(_bar(onSelected: taps.add)));
    await _settle(tester, bridge);

    await tester.pumpWidget(_app(const SizedBox.shrink()));
    await _settle(tester, bridge);

    await bridge.sendTap('home');
    expect(taps, isEmpty);
    expect(tester.takeException(), isNull);
  });

  testWidgets('hidden bars stop exposing themselves to interaction', (
    tester,
  ) async {
    final bridge = _Bridge()..install();
    await tester.pumpWidget(_app(_bar(visible: false)));
    await _settle(tester, bridge);
    expect(bridge.lastState['visible'], isFalse);
    expect(bridge.lastState['interactive'], isFalse);
  });

  test('capabilities are parsed once and cached', () async {
    NativeLiquidGlassNavigation.debugResetCapabilities();
    final messenger =
        TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
    var calls = 0;
    messenger.setMockMethodCallHandler(
      const MethodChannel(NativeLiquidGlassNavigation.capabilitiesChannelName),
      (call) async {
        calls++;
        expect(call.method, 'getCapabilities');
        return {
          'supported': true,
          'effect': 'UIGlassEffect',
          'osVersion': '27.3',
          'deviceModel': 'iPhone',
        };
      },
    );

    final capabilities =
        await NativeLiquidGlassNavigation.prefetchCapabilities();
    expect(capabilities.usesUIGlassEffect, isTrue);
    expect(capabilities.osVersion, '27.3');
    expect(NativeLiquidGlassNavigation.cachedCapabilities, same(capabilities));

    final again = await NativeLiquidGlassNavigation.prefetchCapabilities();
    expect(again, same(capabilities));
    expect(calls, 1);

    messenger.setMockMethodCallHandler(
      const MethodChannel(NativeLiquidGlassNavigation.capabilitiesChannelName),
      null,
    );
  });
}
